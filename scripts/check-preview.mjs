import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
import path from 'node:path';
import assert from 'node:assert/strict';
const require = createRequire(process.env.PLAYWRIGHT_PACKAGE_ROOT + '/package.json');
const { chromium } = require('playwright');
const browser = await chromium.launch({ headless: true, channel: 'msedge' });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto(pathToFileURL(path.resolve('index.html')).href);
  await page.getByRole('heading', { name: '작은 불편, 함께 남기는 변화' }).waitFor();
  await page.screenshot({ path: 'tmp/desktop.png', fullPage: true });
  await page.locator('select[name="district"]').selectOption('유성구');
  await page.locator('input[name="dong"]').fill('신성동');
  await page.locator('textarea[name="content"]').fill('집 앞 도로에 큰 구멍이 생겼어요.');
  await page.getByRole('button', { name: '분류 확인하기' }).click();
  assert.equal(await page.locator('input[name="recommended-category"]').count(), 1);
  assert.equal(await page.locator('#submit-report').isDisabled(), true);
  await page.locator('input[name="recommended-category"][value="road"]').check();
  await page.getByRole('button', { name: '제보 등록하기' }).click();
  await page.getByRole('heading', { name: '체험 제보를 저장했습니다' }).waitFor();
  await page.getByRole('button', { name: '민원 안내 보기', exact: true }).click();
  await page.getByRole('heading', { name: '교통·도로 민원 안내' }).waitFor();
  await page.getByRole('button', { name: '닫기', exact: true }).click();
  await page.getByRole('button', { name: '우리 동네 현황', exact: true }).click();
  await page.getByRole('heading', { name: '선택 지역 · 분야별 현황' }).waitFor();
  assert.equal(await page.locator('.metric-strip strong').first().textContent(), '4');
  await page.screenshot({ path: 'tmp/statistics.png', fullPage: true });
  await page.getByRole('link', { name: '내 제보', exact: true }).click();
  await page.getByRole('button', { name: '해결 완료로 변경', exact: true }).click();
  await page.getByText('작성자 해결 확인', { exact: true }).waitFor();
  await page.reload();
  await page.getByText('작성자 해결 확인', { exact: true }).waitFor();
  await page.getByRole('link', { name: '생활불편 제보' }).click();
  await page.locator('select[name="district"]').selectOption('유성구');
  await page.locator('input[name="dong"]').fill('신성동');
  await page.locator('textarea[name="content"]').fill('하수구에서 악취가 올라와요.');
  await page.getByRole('button', { name: '분류 확인하기' }).click();
  assert.equal(await page.locator('input[name="recommended-category"]').count(), 2);
  assert.equal(await page.locator('#category-select').count(), 0);
  assert.equal(await page.locator('#submit-report').isDisabled(), true);
  await page.locator('input[name="recommended-category"][value="odor"]').check();
  assert.equal(await page.locator('#submit-report').isDisabled(), false);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'tmp/mobile.png', fullPage: true });
  await page.locator('textarea[name="content"]').fill('오늘 학교에서 수학을 공부했어요.');
  assert.equal(await page.locator('input[name="recommended-category"]').count(), 0);
  assert.equal(await page.locator('#submit-report').isDisabled(), true);
  await page.getByRole('button', { name: '분류 확인하기' }).click();
  await page.getByText('관련 분류를 찾기 어려워요', { exact: true }).waitFor();
  assert.equal(await page.locator('input[name="recommended-category"]').count(), 0);
  for (const hash of ['report','board','stats','mine']) {
    await page.goto(pathToFileURL(path.resolve('index.html')).href + '#' + hash);
    await page.locator('h1').waitFor();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, hash + ' overflow');
  }
  assert.deepEqual(errors, []);
  console.log('PASS: desktop/mobile rendering, classification, ties, persistence, guide, stats and own-report status.');
} finally { await browser.close(); }
