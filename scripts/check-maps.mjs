import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
import path from 'node:path';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const require = createRequire(process.env.PLAYWRIGHT_PACKAGE_ROOT + '/package.json');
const { chromium } = require('playwright');
const browser = await chromium.launch({headless:true,channel:'msedge'});
try {
  const page = await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[]; page.on('pageerror',e=>errors.push(e.message));
  await page.goto(pathToFileURL(path.resolve('index.html')).href);
  await page.locator('#location-picker.leaflet-container').waitFor();
  await page.locator('[name=district]').selectOption('유성구');
  await page.locator('[name=dong]').fill('신성동');
  await page.locator('[name=place_text]').fill('테스트 공원 앞 보행로');
  await page.locator('#pick-center').click();
  assert.match(await page.locator('#location-output').innerText(),/선택 위치/);
  await page.locator('#clear-location').click();
  assert.equal(await page.locator('#location-output').innerText(),'위치 미선택');
  const box=await page.locator('#location-picker').boundingBox();
  await page.mouse.click(box.x+box.width*.6,box.y+box.height*.55);
  const location=await page.locator('#location-output').innerText();
  assert.match(location,/선택 위치/);
  await page.locator('[name=content]').fill('테스트 보행로 앞 도로에 구멍이 생겼어요.');
  await page.locator('#analyze').click();
  await page.locator('[name=recommended-category][value=road]').check();
  await page.locator('#submit-report').click();
  await page.getByRole('heading',{name:'체험 제보를 저장했습니다'}).waitFor();
  await page.locator('#success-guide').click();
  await page.locator('#detail-map.leaflet-container').waitFor();
  assert.match(await page.locator('#detail-content').innerText(),/테스트 공원 앞 보행로/);
  await page.locator('[data-close=detail]').click();
  await page.locator('a[data-page=map]').click();
  await page.locator('#heat-map.leaflet-container').waitFor();
  assert.match(await page.locator('.map-metrics').innerText(),/위치 등록\s*1/);
  const painted=await page.locator('.leaflet-heatmap-layer').evaluate(canvas=>{
    const d=canvas.getContext('2d').getImageData(0,0,canvas.width,canvas.height).data;
    for(let i=3;i<d.length;i+=4) if(d[i]>0)return true;
    return false;
  });
  assert.equal(painted,true);
  await mkdir('tmp',{recursive:true});
  await page.screenshot({path:'tmp/map-desktop.png',fullPage:true});
  await page.locator('#map-filters [name=category]').selectOption('road');
  await page.locator('#heat-map').waitFor();
  assert.match(await page.locator('.map-metrics').innerText(),/전체 제보\s*2/);
  await page.locator('[name=map-mode][value=count]').check();
  assert.equal(await page.locator('#heat-legend').isVisible(),false);
  await page.locator('#map-filters [name=status]').selectOption('resolved');
  await page.locator('.map-empty').waitFor();
  assert.match(await page.locator('.map-metrics').innerText(),/위치 등록\s*0/);
  await page.locator('#map-filters [name=main]').selectOption('환경');
  assert.equal(await page.locator('#map-filters [name=category]').inputValue(),'');
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'tmp/map-mobile.png',fullPage:true});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  for(let i=0;i<3;i++){
    await page.locator('a[data-page=report]').click();
    await page.locator('#location-picker.leaflet-container').waitFor();
    await page.locator('a[data-page=map]').click();
    await page.locator('#heat-map.leaflet-container').waitFor();
  }
  await page.reload();
  await page.locator('#heat-map').waitFor();
  assert.match(await page.locator('.map-metrics').innerText(),/위치 등록\s*1/);
  assert.deepEqual(errors,[]);
  console.log('PASS: pin click/clear, location persistence, detail map, nonblank heat canvas, weighted filters, empty state, map cleanup, desktop/mobile. Demo data only.');
} finally {await browser.close();}
