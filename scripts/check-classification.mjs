import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
import path from 'node:path';
import assert from 'node:assert/strict';
const require = createRequire(process.env.PLAYWRIGHT_PACKAGE_ROOT + '/package.json');
const { chromium } = require('playwright');
const browser = await chromium.launch({headless:true,channel:'msedge'});
try {
  const page = await browser.newPage({viewport:{width:1280,height:900}});
  const errors=[]; page.on('pageerror',e=>errors.push(e.message));
  await page.goto(process.env.CHECK_URL || pathToFileURL(path.resolve('index.html')).href);
  await page.locator('#report-form').waitFor();
  if(process.env.CHECK_URL) await page.locator('#mode.live').waitFor();
  await page.locator('select[name="district"]').selectOption('유성구');
  await page.locator('input[name="dong"]').fill('신성동');
  const content=page.locator('textarea[name="content"]');
  await content.fill('불법적인 포스터들이 많이 붙어 있어요. 계속 방치되면 보기에도 좋지 않고 더욱이 어린 아이들이 보게 된다면 더 안 좋을 것 같아요. 빠른 수거 부탁드립니다. 도로 주변이 많이 지저분한 것 같습니다.');
  await page.locator('#analyze').click();
  const choices=page.locator('input[name="recommended-category"]');
  assert.equal(await choices.first().getAttribute('value'),'ad');
  assert.ok(await choices.count()<=5);
  assert.equal(await page.locator('#submit-report').isDisabled(),true);
  await choices.first().check();
  assert.equal(await page.locator('#submit-report').isDisabled(),false);
  await content.fill('도로에 포트홀이 있고 쓰레기와 현수막이 쌓여 있고 가로등과 신호등이 꺼졌고 킥보드가 쓰러져 있어요.');
  assert.equal(await choices.count(),0);
  assert.equal(await page.locator('#submit-report').isDisabled(),true);
  await page.locator('#analyze').click();
  assert.equal(await choices.count(),5);
  await choices.last().check();
  assert.equal(await page.locator('#submit-report').isDisabled(),false);
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:'tmp/classification-five-mobile.png',fullPage:true});
  await content.fill('오늘 학교에서 수학을 공부했어요.');
  await page.locator('#analyze').click();
  assert.equal(await choices.count(),0);
  assert.equal(await page.locator('#submit-report').isDisabled(),true);
  assert.deepEqual(errors,[]);
  console.log('PASS: poster first, five choices, explicit selection, edit reset, unrelated text, mobile layout. No reports submitted.');
} finally {await browser.close();}
